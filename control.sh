#!/usr/bin/env bash
# =============================================================================
# control.sh — Generic Docker stack control (auto-detecting)
#
# Usage:
#   ./control.sh create [dev|prod]             first-time setup: .env, secrets, start stack
#   ./control.sh setup [--force] [dev|prod]    create/refresh .env, start stack
#   ./control.sh start                         start the stack
#   ./control.sh stop                          stop and remove containers
#   ./control.sh restart                       restart containers (no rebuild)
#   ./control.sh rebuild                       git pull + rebuild images + recreate
#   ./control.sh status                        show container + version status
#   ./control.sh logs [service]                tail app log (default) or docker logs (service)
#   ./control.sh tunnel quick                  expose app via trycloudflare (no account)
#   ./control.sh tunnel setup                  one-time named tunnel provisioning via API
#   ./control.sh tunnel named                  run provisioned named tunnel (compose add-on)
#   ./control.sh tunnel url                    print current remote URL
#   ./control.sh tunnel status                 show tunnel process state
#   ./control.sh tunnel stop                   stop project's cloudflared
#   ./control.sh reset [--yes]                 DESTRUCTIVE wipe + fresh setup
#   ./control.sh help                          show this help
#
# No configuration file needed — this script inspects the layout and detects:
#   * layout      single directory (the checkout is the install root) or a
#                 split install (this script is reached through a symlink and
#                 the checkout sits beside the install root)
#   * framework   (laravel when artisan+composer.json exist, node for any
#                 package.json, otherwise generic), read from the checkout
#   * compose     which docker-compose files exist (dev/prod/override) in the
#                 install root, as regular files or as symlinks into the checkout
#   * build paths every compose build context must resolve to a directory that
#                 holds the checkout's build inputs, checked before teardown
#   * main service (docker compose config --services, preferring a name that
#                 matches the install root, then app/web, then the first service)
#   * secrets     empty *_KEY / *_SECRET / *_PASSWORD / *_TOKEN / APP_KEY
#                 entries in .env(.example) are generated during setup
#   * version     APP_VERSION/GIT_SHA build args are injected only when the
#                 Dockerfile / compose files actually use them, from the checkout
#   * reset scope SQLite files and gitignored data dirs that exist on disk
#
# Layouts
# -------
#   single directory  the checkout is the install root
#                     (git clone <repo> <app> && cd <app>)
#
#   split install     the install root holds configuration and a control.sh
#                     symlink into a checkout that lives beside it:
#
#                       /opt/containers/<instance>/       <- install root
#                       ├── .env                          <- hand-crafted config
#                       ├── .gitignore                    <- ignores <app>-git/
#                       ├── docker-compose.yml            <- local file or symlink
#                       ├── docker-compose.override.yml   <- per-host overrides
#                       ├── control.sh -> <app>-git/control.sh
#                       └── <app>-git/                    <- application checkout
#
#                     Compose runs from the install root; source, Dockerfiles
#                     and build inputs come from the checkout. A nested
#                     checkout is added to the install root's .gitignore as a
#                     single anchored rule and is never recorded as a gitlink.
#
# Generated by the lmt-skills-docker-control-sh skill. Repo-specific hooks such as admin
# password resets were intentionally removed; re-add them per project if needed.
# =============================================================================

set -euo pipefail

# --- Layout resolution -----------------------------------------------------
# Follow symlinks so an install-root `control.sh` symlink still finds the
# checkout it points at.
resolve_symlink() {
    local path="$1" dir
    while [ -L "$path" ]; do
        dir="$(cd -P "$(dirname "$path")" && pwd)"
        path="$(readlink "$path")"
        case "$path" in
            /*) ;;
            *) path="${dir}/${path}" ;;
        esac
    done
    printf '%s\n' "$path"
}

SCRIPT_PATH="$(resolve_symlink "${BASH_SOURCE[0]}")"
case "$SCRIPT_PATH" in
    /*) ;;
    *) SCRIPT_PATH="$(pwd)/${SCRIPT_PATH}" ;;
esac
CODE_DIR="$(cd "$(dirname "$SCRIPT_PATH")" && pwd)"
SCRIPT_PATH="${CODE_DIR}/$(basename "$SCRIPT_PATH")"
INVOKED_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# The invoked directory is the install root only when the script was reached
# through a symlink, that directory is not itself a checkout, and it either
# contains the checkout as a child or already holds install configuration. A
# symlink dropped somewhere unrelated (e.g. ~/bin) keeps the single-directory
# behaviour instead of reading .env next to it.
INSTALL_DIR="$CODE_DIR"
SPLIT_INSTALL=0
if [ "$INVOKED_DIR" != "$CODE_DIR" ] && [ ! -f "$INVOKED_DIR/artisan" ]; then
    checkout_is_child=0
    case "$CODE_DIR" in
        "$INVOKED_DIR"/*) checkout_is_child=1 ;;
    esac
    if [ "$checkout_is_child" -eq 1 ] \
        || [ -f "$INVOKED_DIR/.env" ] \
        || [ -f "$INVOKED_DIR/docker-compose.yml" ] \
        || [ -f "$INVOKED_DIR/compose.yaml" ]; then
        INSTALL_DIR="$INVOKED_DIR"
        SPLIT_INSTALL=1
    fi
fi

cd "$INSTALL_DIR"

# ---------------------------------------------------------------------------
# -- Helpers ---------------------------------------------------------------
# ---------------------------------------------------------------------------

log()    { printf '\033[1;36m==> %s\033[0m\n' "$*"; }
warn()   { printf '\033[1;33m!!  %s\033[0m\n' "$*"; }
die()    { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# -- Layout helpers ---------------------------------------------------------
# ---------------------------------------------------------------------------

# Print the detected layout (split installs only — the single-directory case
# is the default and needs no explanation).
announce_layout() {
    [ "$SPLIT_INSTALL" -eq 1 ] || return 0
    log "Split install: install root ${INSTALL_DIR}, code ${CODE_DIR}"
}

# How the compose files (which live in the install root) reference the
# checkout: relative when it sits inside the install root, absolute otherwise.
# The `./` prefix matters — without it compose would read `<app>-git` as a
# named volume instead of a bind-mount source.
code_dir_ref() {
    case "$CODE_DIR" in
        "$INSTALL_DIR"/*) printf './%s\n' "${CODE_DIR#"$INSTALL_DIR"/}" ;;
        *) printf '%s\n' "$CODE_DIR" ;;
    esac
}

# Keep the generic code-directory key in step with the detected layout. Compose
# files read Dockerfiles, config and (dev) the code bind mount from
# ${CONTROL_CODE_DIR:-.}, so a split install sets it and a single-directory
# install leaves it unset.
ensure_layout_env() {
    if [ "$SPLIT_INSTALL" -eq 1 ]; then
        local ref
        ref="$(code_dir_ref)"
        [ "$(get_env CONTROL_CODE_DIR)" = "$ref" ] || set_env CONTROL_CODE_DIR "$ref"
        export CONTROL_CODE_DIR="$ref"
    elif grep -qE '^CONTROL_CODE_DIR=' "$ENV_FILE" 2>/dev/null; then
        unset_env CONTROL_CODE_DIR
    fi
}

# Path of the checkout relative to the install root, or empty when it is not
# nested (an absolute checkout has no parent ignore rule to add).
nested_checkout_path() {
    case "$CODE_DIR" in
        "$INSTALL_DIR"/*) printf '%s\n' "${CODE_DIR#"$INSTALL_DIR"/}" ;;
        *) printf '\n' ;;
    esac
}

# A Git-tracked install root must not record the checkout: a nested repository
# becomes a mode-160000 gitlink (a submodule entry) that nobody can clone.
# Append exactly one anchored ignore rule and verify it. Never touch the index:
# an already tracked checkout is a hard stop with the repair command.
ensure_parent_git_ignore() {
    [ "$SPLIT_INSTALL" -eq 1 ] || return 0

    local rel
    rel="$(nested_checkout_path)"
    [ -n "$rel" ] || return 0

    git -C "$INSTALL_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1 || return 0

    if [ -n "$(git -C "$INSTALL_DIR" ls-files --stage -- "$rel" 2>/dev/null)" ]; then
        die "the checkout '${rel}' is tracked by the install root's Git repository.
    A nested repository recorded as a gitlink (mode 160000) is a submodule
    entry, not the configuration this repository should track. Nothing was
    changed. Untrack it from ${INSTALL_DIR}, then re-run:
      git rm --cached -r '${rel}'
      printf '/%s/\\n' '${rel}' >> .gitignore
    Host configuration belongs in .env, the compose files or
    docker-compose.override.yml — never in the application checkout."
    fi

    git -C "$INSTALL_DIR" check-ignore -q -- "$rel" && return 0

    local prefix pattern ignore_file
    prefix="$(git -C "$INSTALL_DIR" rev-parse --show-prefix 2>/dev/null)"
    pattern="/${prefix}${rel}/"
    ignore_file="${INSTALL_DIR}/.gitignore"

    if [ -s "$ignore_file" ] && [ -n "$(tail -c 1 "$ignore_file")" ]; then
        printf '\n' >> "$ignore_file"
    fi
    printf '%s\n' "$pattern" >> "$ignore_file"
    log "Ignoring the checkout in ${ignore_file} (${pattern})."

    if ! git -C "$INSTALL_DIR" check-ignore -q -- "$rel"; then
        die "'${pattern}' was added to ${ignore_file} but Git still reports '${rel}' as unignored.
    Check for a conflicting rule that re-includes the checkout, e.g. a
    later '!${rel}' line."
    fi
}

# The install root owns its compose files. Create a missing base file from the
# checkout so a split install needs nothing but a symlink and .env, keep every
# existing file exactly as it is (a regular file is host-owned; a symlink is
# host-owned and followed), and never create or replace an override file.
ensure_compose_files() {
    [ "$SPLIT_INSTALL" -eq 1 ] || return 0

    local file
    for file in docker-compose.yml docker-compose.prod.yml compose.yaml compose.yml; do
        [ -e "${CODE_DIR}/${file}" ] || continue
        [ -L "${CODE_DIR}/${file}" ] && continue

        if [ -L "${INSTALL_DIR}/${file}" ]; then
            # A symlinked base file follows the checkout; never write through it.
            continue
        fi

        if [ ! -e "${INSTALL_DIR}/${file}" ]; then
            cp "${CODE_DIR}/${file}" "${INSTALL_DIR}/${file}"
            log "Created ${file} from the checkout."
        elif ! cmp -s "${CODE_DIR}/${file}" "${INSTALL_DIR}/${file}"; then
            warn "${file} differs from the checkout's copy."
            warn "  Compare: diff -u '${CODE_DIR}/${file}' '${INSTALL_DIR}/${file}'"
            warn "  Update:  cp '${CODE_DIR}/${file}' '${INSTALL_DIR}/${file}'"
            warn "  (host-specific tweaks belong in docker-compose.override.yml)"
        fi
    done
}

# ---------------------------------------------------------------------------
# -- Detection -------------------------------------------------------------
