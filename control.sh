# -- Project hooks (dumbdock) -----------------------------------------------
# ---------------------------------------------------------------------------
# dumbdock publishes DUMBDOCK_PORT only; APP_PORT is a generic-script concept.
# Everything below keeps the generic commands working for this project without
# adding new settings of its own.

# The port the dashboard is published on: APP_PORT when a project sets it, then
# dumbdock's own key.
app_port() {
    local port
    port="$(get_env APP_PORT)"
    [ -n "$port" ] || port="$(get_env DUMBDOCK_PORT)"
    printf '%s\n' "$port"
}

# Is TCP port $1 free on 127.0.0.1? Returns 0 when free, 1 when taken.
port_free() {
    local port="$1"
    if command -v python3 >/dev/null 2>&1; then
        python3 -c "import socket,sys; s=socket.socket(); s.settimeout(1); sys.exit(0 if s.connect_ex(('127.0.0.1', int(sys.argv[1]))) != 0 else 1)" "$port" 2>/dev/null
    else
        (echo > "/dev/tcp/127.0.0.1/${port}") 2>/dev/null && return 1 || return 0
    fi
}

# dumbdock-only: if DUMBDOCK_PORT is taken by another process, bump it until a
# free port is found (bounded) and write the result back to .env, so `setup`
# never dies with "bind: address already in use". Skipped when our own stack is
# already running (recreate rebinds the same port fine).
ensure_free_dumbdock_port() {
    has_key DUMBDOCK_PORT || return 0
    local old port tries=0
    old="$(get_env DUMBDOCK_PORT)"
    port="$old"
    [ -n "$port" ] || port=8080
    if ! [[ "$port" =~ ^[0-9]+$ ]]; then
        warn "DUMBDOCK_PORT='${port}' is not numeric — leaving as-is."
        return 0
    fi
    if docker compose ps "$MAIN_SERVICE" 2>/dev/null | grep -q "Up"; then
        return 0
    fi
    while ! port_free "$port"; do
        tries=$((tries + 1))
        if [ "$tries" -ge 100 ]; then
            die "No free port found starting from ${port} (tried 100 ports)."
        fi
        port=$((port + 1))
    done
    if [ "$port" != "$old" ]; then
        set_env DUMBDOCK_PORT "$port"
        log "Port ${old} is already in use — using DUMBDOCK_PORT=${port} instead."
    fi
}

# dumbdock-only: the named tunnel runs from the optional compose add-on
# docker-compose.override.yml, which Docker Compose merges into the base file
# automatically. Create it from the committed example on first use, and never
# rewrite an override the operator already owns.
tunnel_ensure_override() {
    local override="docker-compose.override.yml"
    local example="${CODE_DIR}/docker-compose.override.yml.example"
    if [ ! -f "$override" ]; then
        if [ ! -f "$example" ]; then
            die "Missing ${override} and its example (${example}) — restore the checkout and retry."
        fi
        cp "$example" "$override"
        log "Created ${override} from docker-compose.override.yml.example."
        return 0
    fi
    if ! grep -qE '^[[:space:]]*cloudflared:[[:space:]]*$' "$override"; then
        die "${override} exists but defines no 'cloudflared' service. Add the service from docker-compose.override.yml.example, or delete the file and re-run."
    fi
}

