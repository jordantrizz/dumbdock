FRAMEWORK="generic"
MAIN_SERVICE=""
COMPOSE_FILES="docker-compose.yml"

detect_framework() {
    if { [ -f "${CODE_DIR}/artisan" ] || [ -f artisan ]; } &&
       { [ -f "${CODE_DIR}/composer.json" ] || [ -f composer.json ]; }; then
        FRAMEWORK="laravel"
    elif [ -f "${CODE_DIR}/package.json" ] || [ -f package.json ]; then
        FRAMEWORK="node"
    else
        FRAMEWORK="generic"
    fi
}

detect_main_service() {
    local services names preferred
    if ! services="$(docker compose config --services 2>/dev/null)"; then
        MAIN_SERVICE="app"
        return
    fi
    [ -z "$services" ] && { MAIN_SERVICE="app"; return; }
    names="$(basename "$INSTALL_DIR")
app
web
server
www"

    preferred="$(printf '%s\n' "$names" | while read -r name; do
        printf '%s\n' "$services" | grep -qx "$name" && { printf '%s' "$name"; break; }
    done)" || true
    if [ -n "$preferred" ]; then
        MAIN_SERVICE="$preferred"
    else
        MAIN_SERVICE="$(printf '%s\n' "$services" | head -1)"
    fi
}

# Collect the compose files that actually exist, preferring explicit overrides.
# A symlinked base file counts as present and is never dereferenced here.
detect_compose_files() {
    local files="" candidate
    for candidate in docker-compose.yml docker-compose.prod.yml docker-compose.override.yml compose.yaml compose.yml; do
        if [ -e "$candidate" ]; then
            [ -n "$files" ] && files="$files:"
            files="$files$candidate"
        fi
    done
    if [ -n "$files" ]; then
        COMPOSE_FILES="$files"
    fi
    return 0
}

# Does the Dockerfile / compose setup consume APP_VERSION or GIT_SHA? The
# Dockerfile lives in the checkout; the compose files live in the install root.
uses_version_args() {
    grep -qsE 'APP_VERSION|GIT_SHA' \
        "${CODE_DIR}/Dockerfile" "${CODE_DIR}"/Dockerfile.* 2>/dev/null ||
        grep -qsE 'APP_VERSION|GIT_SHA' Dockerfile Dockerfile.* 2>/dev/null ||
        grep -qsE '\$\{?(APP_VERSION|GIT_SHA)\}?' docker-compose*.yml compose.*.y?ml 2>/dev/null
}

# ---------------------------------------------------------------------------
# -- Build-input verification ----------------------------------------------
# ---------------------------------------------------------------------------

# Print each build unit as "<context>|<dockerfile>", one per line, from the
# effective compose configuration (after override files).
build_units() {
    docker compose config 2>/dev/null | awk '
        /^[[:space:]]+context:/ {
            if (ctx != "") print ctx "|" df
            ctx = $2; df = ""; next
        }
        /^[[:space:]]+dockerfile:/ { df = $2; next }
        END { if (ctx != "") print ctx "|" df }
    ' || true
}

# The build contexts alone (used for the checkout-coverage check).
build_contexts() {
    build_units | while IFS='|' read -r context _; do
        [ -n "$context" ] && printf '%s\n' "$context"
    done
}

# Do the compose files route any path through ${CONTROL_CODE_DIR}?
compose_uses_code_dir() {
    local file
    for file in docker-compose.yml docker-compose.prod.yml docker-compose.override.yml compose.yaml compose.yml; do
        [ -e "$file" ] || continue
        grep -q 'CONTROL_CODE_DIR' "$file" 2>/dev/null && return 0
    done
    return 1
}

# A Dockerfile's COPY paths are resolved against the *build context*, not the
# Dockerfile's directory. In a split install `context: .` therefore builds the
# install root (no Dockerfile, no docker/) and fails with `failed to compute
# cache key: "/docker/..."` — the `transferring context: 2B` line is the tell.
# Refuse early, while the current deployment is still running, and never
# rewrite a host-owned compose file.
verify_build_contexts() {
    command -v docker >/dev/null 2>&1 || return 0

    local units context dockerfile dockerfile_path resolved found=0
    units="$(build_units)"
    [ -n "$units" ] || return 0

    while IFS='|' read -r context dockerfile; do
        [ -n "$context" ] || continue

        if [ ! -d "$context" ]; then
            die "build context '${context}' does not exist.
    Docker resolves a Dockerfile's COPY paths against the build context, so
    this cannot build and the stack is left untouched. Fix the compose file
    in ${INSTALL_DIR} — point build.context at the checkout through
    \${CONTROL_CODE_DIR:-.} — or put the host-specific change in
    docker-compose.override.yml."
        fi

        # A build needs its Dockerfile inside the context. `context: .` in a
        # split install resolves (to the install root) and still has none,
        # which is exactly how the pre-split compose file fails at COPY time.
        dockerfile_path="${dockerfile:-Dockerfile}"
        case "$dockerfile_path" in
            /*) ;;
            *) dockerfile_path="${context}/${dockerfile_path}" ;;
        esac
        if [ ! -f "$dockerfile_path" ]; then
            die "build context '${context}' has no Dockerfile (${dockerfile_path}).
    Docker resolves a Dockerfile's COPY paths against the build context, so
    this cannot build and the stack is left untouched. In a split install the
    Dockerfile lives in the checkout (${CODE_DIR}); point build.context at
    \${CONTROL_CODE_DIR:-.} in ${INSTALL_DIR}/docker-compose.yml, or put the
    host-specific change in docker-compose.override.yml."
        fi
    done <<EOF
$units
EOF

    compose_uses_code_dir || return 0

    local eff="${CONTROL_CODE_DIR:-.}"
    if [ ! -d "$eff" ]; then
        die "\${CONTROL_CODE_DIR:-.} is referenced by the compose files but resolves to
    '${CONTROL_CODE_DIR:-<unset>}' (not a directory). The compose files in
    ${INSTALL_DIR} build from the checkout, which is ${CODE_DIR}."
    fi

    # Building from the checkout means at least one effective context must
    # resolve into it; an unset key in a single-directory install resolves to
    # the checkout itself, which is correct.
    while IFS='|' read -r context _; do
        [ -n "$context" ] || continue
        resolved="$(cd "$context" 2>/dev/null && pwd)" || continue
        case "$resolved" in
            "$CODE_DIR"|"$CODE_DIR"/*) found=1 ;;
        esac
    done <<EOF
$units
EOF

    if [ "$found" -eq 0 ]; then
        die "the compose files build from \${CONTROL_CODE_DIR:-.} but no build context
    resolves into the checkout (${CODE_DIR}). Contexts seen:
$(build_contexts | sed 's/^/      /')
    Point build.context at \${CONTROL_CODE_DIR:-.} so the Dockerfile and its
    COPY paths come from the checkout instead of ${INSTALL_DIR}."
    fi
}

# Common preparation for every command that touches install-root state: the
# .env, the parent Git ignore rule, the compose files and the checkout
# reference must all agree before Compose runs.
prepare_install() {
    ensure_env_file
    ensure_parent_git_ignore
    ensure_compose_files
    ensure_layout_env
    # Copying a base file can change which compose files exist.
    detect_compose_files
}

